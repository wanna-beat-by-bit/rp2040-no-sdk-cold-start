#ifndef REGISTERS_H
#define REGISTERS_H

#include <stdint.h>

#define  REG(addr) (*(volatile uint32_t *)(addr))

#define APB_ATOMIC_XOR 0x1000u
#define APB_ATOMIC_SET 0x2000u
#define APB_ATOMIC_CLR 0x3000u

#define RESETS_BASE 0x4000c000u
#define RESETS_RESET 0x0u
#define RESETS_RESET_DONE 0x8u
#define RESETS_RESET_IO_BANK0_LSB 5u
#define RESETS_RESET_PADS_BANK0_LSB 8u

#define IO_BANK0_BASE 0x40014000u
#define IO_BANK0_GPIO25_CTRL 0x0ccu
#define IO_BANK0_GPIO_CTRL_FUNCSEL_LSB 0u
#define IO_BANK0_GPIO_CTRL_FUNCSEL_WIDTH 5u
#define IO_BANK0_GPIO_CTRL_FUNCSEL_MASK \
    (((1u << IO_BANK0_GPIO_CTRL_FUNCSEL_WIDTH) - 1u) << IO_BANK0_GPIO_CTRL_FUNCSEL_LSB)
#define IO_BANK0_GPIO_CTRL_FUNCSEL_SIO 5u

#define SIO_BASE 0xd0000000u
#define SIO_GPIO_IN 0x004u
#define SIO_GPIO_OUT 0x010u
#define SIO_GPIO_OUT_SET 0x014u
#define SIO_GPIO_OUT_CLR 0x018u
#define SIO_GPIO_OUT_XOR 0x01cu
#define SIO_GPIO_OE 0x020u
#define SIO_GPIO_OE_SET 0x024u
#define SIO_GPIO_OE_CLR 0x028u
#define SIO_GPIO_OE_XOR 0x02cu

#define GPIO25_BIT 25u

#endif
